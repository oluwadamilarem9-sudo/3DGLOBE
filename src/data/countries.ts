export const getCountryByName = (name: string): Country | undefined => {
  return countriesData.find(country => 
    country.name.toLowerCase() === name.toLowerCase() ||
    country.officialName.toLowerCase() === name.toLowerCase()
  );
};

export const getCountryByISO = (isoCode: string): Country | undefined => {
  return countriesData.find(country => country.isoCode === isoCode);
};

export const searchCountries = (query: string): Country[] => {
  const lowerQuery = query.toLowerCase();
  return countriesData.filter(country =>
    country.name.toLowerCase().includes(lowerQuery) ||
    country.officialName.toLowerCase().includes(lowerQuery) ||
    country.capital.toLowerCase().includes(lowerQuery)
  );
};
